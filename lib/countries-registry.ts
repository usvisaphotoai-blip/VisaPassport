/** Index by country_code (upper-cased) and by id */
const countryByCode = new Map<string, CentralCountry>();
const countryById = new Map<string, CentralCountry>();
for (const c of CANONICAL_COUNTRIES) {
  countryByCode.set(c.country_code.toUpperCase(), c);
  countryById.set(c.id.toLowerCase(), c);
  // Add common aliases
  if (c.country_code === "CHE") countryByCode.set("CH", c);
  if (c.country_code === "GB") countryByCode.set("UK", c);
  if (c.country_code === "PER") countryByCode.set("PE", c);
}

export function getCentralCountry(codeOrId?: string): CentralCountry | undefined {
  if (!codeOrId) return undefined;
  const clean = codeOrId.trim();
  const byCode = countryByCode.get(clean.toUpperCase());
  if (byCode) return byCode;
  const byId = countryById.get(clean.toLowerCase());
  if (byId) return byId;

  const baseSlug = clean
    .toLowerCase()
    .replace(/-passport$/, "")
    .replace(/-visa$/, "");
  const directMatch = CANONICAL_COUNTRIES.find(
    (c) =>
      c.id.startsWith(baseSlug) ||
      c.country_name.toLowerCase() === baseSlug ||
      c.country_name.toLowerCase().replace(/\s+/g, "-") === baseSlug
  );
  return directMatch;
}

export function formatDualCountryLabel(
  country: CentralCountry,
  lang: "de" | "fr" | "es" | "pt" | "en"
): string {
  if (lang === "en") return country.country_name;
  const native = country.translations[lang] || country.country_name;
  // If native name is identical to English, just show it once
  if (native.toLowerCase() === country.country_name.toLowerCase()) {
    return native;
  }
  return `${native} (${country.country_name})`;
}

/** Formats a document label with dual-language country names */
export function formatLocalizedDocLabel(
  country: CentralCountry,
  lang: "de" | "fr" | "es" | "pt" | "en",
  documentKind: "passport" | "visa" = "passport"
): string {
  if (country.id === "foto-3x4") {
    if (lang === "de") return "Foto 3x4 (Brasilien) – Standard";
    if (lang === "fr") return "Photo 3x4 (Brésil) – Standard";
    if (lang === "es") return "Foto 3x4 (Brasil) – Estándar";
    if (lang === "pt") return "Foto 3x4 (Brasil)";
    return "Photo 3x4 (Brazil)";
  }
  const dualCountry = formatDualCountryLabel(country, lang);
  if (lang === "de") {
    return documentKind === "visa"
      ? `${dualCountry} – Visum`
      : `${dualCountry} – Reisepass`;
  }
  if (lang === "fr") {
    return documentKind === "visa"
      ? `${dualCountry} – Photo Visa`
      : `${dualCountry} – Photo Passeport`;
  }
  if (lang === "es") {
    return documentKind === "visa"
      ? `${dualCountry} – Visa`
      : `${dualCountry} – Pasaporte`;
  }
  if (lang === "pt") {
    return documentKind === "visa"
      ? `${dualCountry} – Visto`
      : `${dualCountry} – Passaporte`;
  }
  return documentKind === "visa"
    ? `${country.country_name} Visa`
    : `${country.country_name} Passport`;
}

/** Converts a CentralCountry to standard DocumentType used in tools */
export function toDocumentType(
  country: CentralCountry,
  lang: "de" | "fr" | "es" | "pt" | "en" = "en"
): DocumentType {
  const label = formatLocalizedDocLabel(country, lang, country.document_type === "visa" ? "visa" : "passport");
  const size = `${country.width_mm}×${country.height_mm} mm (${country.width_px}×${country.height_px} px)`;
  return {
    id: country.id,
    label,
    size,
    bg_color: country.bg_color,
    country: country.country_name,
    flag: country.flag,
    price: country.price,
    printSize: country.print_size,
  };
}

/** Returns all central countries converted to DocumentTypes for a specific language */
export function getAllCentralDocumentTypes(
  lang: "de" | "fr" | "es" | "pt" | "en" = "en"
): DocumentType[] {
  return CANONICAL_COUNTRIES.map((c) => toDocumentType(c, lang));
}
